/**
 * Wyckoff phase classification (Zenith v3.1).
 * Closed vocabulary — see D:\zenith_saas\algo\algo_wyckoff.py classify_zenith_v3_1().
 */
export type Phase =
  | "SOS"
  | "UPTHRUST"
  | "ABSORB"
  | "SPRING"
  | "DISTRI"
  | "ACCUM"
  | "NEUTRAL";

export const PHASES: readonly Phase[] = [
  "SOS",
  "UPTHRUST",
  "ABSORB",
  "SPRING",
  "DISTRI",
  "ACCUM",
  "NEUTRAL",
] as const;

/** Accumulation-leaning phases (buy-side). */
export const BUY_PHASES: readonly Phase[] = ["SOS", "SPRING", "ABSORB", "ACCUM"];

/** Distribution-leaning phases (sell-side). */
export const SELL_PHASES: readonly Phase[] = ["UPTHRUST", "DISTRI"];

/**
 * One ticker row from /api/flow.
 * Monetary fields (sm_val, bm_val, mf_plus, mf_minus, net_mf, vwap_*) are in Juta
 * (millions of IDR).
 */
export interface TickerRow {
  ticker: string;
  /** SM − BM. Null when either side is unknown. */
  clean_money: number | null;
  /** Smart Money value, Juta. */
  sm_val: number | null;
  /** Bad Money value, Juta. */
  bm_val: number | null;
  /** SM as % of total value (0–100). */
  rsm: number | null;
  mf_plus: number | null;
  mf_minus: number | null;
  net_mf: number | null;
  gain_pct: number | null;
  price: number | null;
  tx: number;
  /** Null when the ticker has no analytics for the day. */
  phase: Phase | null;
  action: string | null;
  watch: string | null;
  /** SM Relative Intensity. */
  sri: number | null;
  /** Money Energy Score: |gain| / sri. */
  mes: number | null;
  volx_gap: number | null;
  /** Sell pressure ratio (tx_bm / total_tx). */
  rpr: number | null;
  atr_pct: number | null;
  sm_sma10: number | null;
  bm_sma10: number | null;
  vwap_sm: number | null;
  vwap_bm: number | null;
  ma5: number | null;
  ma13: number | null;
  ma34: number | null;
  ma200: number | null;
  rsi14: number | null;
  /** Consecutive clean-money streak, days. */
  cm_streak: number | null;
  ma_structure: string | null;
  /** Indonesian narrative text, generated by the backend. Displayed verbatim. */
  narrative: string | null;
}

/** Aggregate totals across all tickers, from /api/flow. */
export interface FlowTotals {
  sm: number;
  bm: number;
  mf_plus: number | null;
  mf_minus: number | null;
  net_cm: number;
  net_mf: number | null;
  count: number;
}

/** Response body of GET /api/flow. */
export interface FlowResponse {
  tickers: TickerRow[];
  totals: FlowTotals;
  /** DD-MM-YYYY */
  date_from: string;
  /** DD-MM-YYYY */
  date_to: string;
}

/** One row of the SM or BM transaction tape, from /api/transactions. */
export interface TransactionRow {
  /** DD-MM-YYYY */
  date: string;
  time: string;
  price: number | null;
  gain_pct: number | null;
  /** Raw MF delta string as received. */
  mf: string | null;
  /** Numeric MF delta. */
  mf_num: number | null;
  vol_x: number | null;
  signal: string | null;
}

/** Response body of GET /api/transactions. */
export interface TransactionsResponse {
  ticker: string;
  sm: TransactionRow[];
  bm: TransactionRow[];
  sm_count: number;
  bm_count: number;
}

/** An empty tape for a ticker with no transactions. */
export function emptyTransactions(ticker: string): TransactionsResponse {
  return { ticker, sm: [], bm: [], sm_count: 0, bm_count: 0 };
}
